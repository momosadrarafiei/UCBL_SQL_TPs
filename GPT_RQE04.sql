SELECT nomF, type
FROM FORETS f
INNER JOIN GESTIONNAIRES g
ON f.idG = g.idG;

-- E02
SELECT nomG, nomF
FROM GESTIONNAIRES g
INNER JOIN FORETS f
ON g.idG = f.idG;

-- E03
